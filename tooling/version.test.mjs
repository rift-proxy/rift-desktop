import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, readlinkSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import test from "node:test";
import { checkVersions } from "./release-check.mjs";
import { setVersion } from "./version.mjs";

const versionFiles = ["Cargo.toml", "desktop/package.json", "desktop/src-tauri/tauri.conf.json", "Cargo.lock", "fuzz/Cargo.lock"];
const source = "registry+https://github.com/rust-lang/crates.io-index";
function locked(name, version, dependencies = [], external = false) {
  return `[[package]]\nname = "${name}"\nversion = "${version}"\n` +
    (external ? `source = "${source}"\nchecksum = "${"a".repeat(64)}"\n` : "") +
    (dependencies.length ? `dependencies = [\n${dependencies.map((ref) => ` "${ref}",\n`).join("")}]\n` : "") + "\n";
}
function fixture(t) {
  const base = mkdtempSync(path.join(tmpdir(), "rift-version-test-"));
  t.after(() => rmSync(base, { recursive: true, force: true }));
  const put = (name, text) => {
    mkdirSync(path.dirname(path.join(base, name)), { recursive: true });
    writeFileSync(path.join(base, name), text);
  };
  const get = (name) => readFileSync(path.join(base, name), "utf8");
  put("Cargo.toml", '# Unrelated 1.2.3 must stay unchanged\n[workspace]\nmembers = ["core", "desktop/src-tauri"]\n\n[workspace.package]\nlicense = "MIT"\nversion  =  "1.2.3"  # explicit app version\nedition = "2021"\npublish = false\n\n[profile.release]\ndebug = "line-tables-only"\n');
  put("desktop/package.json", '{\n\t"name": "@rift/desktop",\n\t"version" : "1.2.3",\n\t"private": true,\n\t"config": {"version":"1.2.3", "label":"version"},\n\t"dependencies": {"third-party":"1.2.3"}\n}\n');
  put("desktop/src-tauri/tauri.conf.json", '{ "productName": "Rift", "version": "1.2.3", "plugins": {"example":{"version":"1.2.3"}} }\n');
  const external = locked("third-party", "1.2.3", [], true) + locked("third-party", "2.0.0", [], true) + locked("rift-core-utils", "1.2.3", [], true);
  const header = "# This file is automatically @generated by Cargo.\nversion = 4\n\n";
  put("Cargo.lock", header + locked("rift-core", "1.2.3", ["third-party 1.2.3", "rift-core-utils"]) + locked("rift-desktop", "1.2.3", ["rift-core", `third-party 2.0.0 (${source})`]) + external);
  put("fuzz/Cargo.toml", '[package]\nname = "rift-fuzz"\nversion = "0.0.0"\npublish = false\n\n[dependencies]\nrift-core = { path = "../core" }\n\n[workspace]\nmembers = ["."]\n');
  put("fuzz/Cargo.lock", header + locked("rift-core", "1.2.3", ["third-party 1.2.3"]) + locked("rift-fuzz", "0.0.0", ["rift-core", "rift-core-utils"]) + external);
  put("CHANGELOG.md", "Owner's uncommitted release notes\n");
  put("core/src/lib.rs", "// Owner's uncommitted code change\n");
  put(".git/HEAD", "ref: refs/heads/local-work\n");
  return { base, put, get };
}
function snapshot(base) {
  const result = new Map();
  function visit(directory, prefix = "") {
    for (const name of readdirSync(directory).sort()) {
      const relative = prefix + name;
      const file = path.join(directory, name);
      const stat = lstatSync(file);
      if (stat.isSymbolicLink()) result.set(relative, `symlink:${readlinkSync(file)}`);
      else if (stat.isDirectory()) { result.set(`${relative}/`, "directory"); visit(file, `${relative}/`); }
      else result.set(relative, readFileSync(file, "utf8"));
    }
  }
  visit(base);
  return result;
}
function expectedUpdate(before, next) {
  const expected = new Map(before);
  expected.set("Cargo.toml", before.get("Cargo.toml").replace('version  =  "1.2.3"', `version  =  "${next}"`));
  expected.set("desktop/package.json", before.get("desktop/package.json").replace('"version" : "1.2.3"', `"version" : "${next}"`));
  expected.set("desktop/src-tauri/tauri.conf.json", before.get("desktop/src-tauri/tauri.conf.json").replace('"version": "1.2.3"', `"version": "${next}"`));
  for (const file of ["Cargo.lock", "fuzz/Cargo.lock"])
    expected.set(file, before.get(file).replace(/(name = "rift-(?:core|desktop)"\nversion = ")1\.2\.3"/g, `$1${next}"`));
  return expected;
}
function installCli(f) {
  mkdirSync(path.join(f.base, "tooling"));
  for (const file of ["release-check.mjs", "version.mjs"])
    copyFileSync(path.join(import.meta.dirname, file), path.join(f.base, "tooling", file));
  return path.join(f.base, "tooling/version.mjs");
}

test("an explicit version updates exactly five files without touching owner edits or external packages", (t) => {
  const f = fixture(t);
  const before = snapshot(f.base);
  assert.equal(setVersion("2.4.6", f.base), "2.4.6");
  assert.equal(checkVersions("v2.4.6", f.base), "2.4.6");
  assert.deepEqual(snapshot(f.base), expectedUpdate(before, "2.4.6"));
  assert.match(f.get("fuzz/Cargo.lock"), /name = "rift-fuzz"\nversion = "0\.0\.0"/);
});

test("qualified local dependencies are updated in both locks, including references from external packages", (t) => {
  const f = fixture(t);
  for (const file of ["Cargo.lock", "fuzz/Cargo.lock"])
    f.put(file, f.get(file).replace(' "rift-core",', ' "rift-core 1.2.3",') + locked("local-user", "1.2.3", file === "Cargo.lock" ? ["rift-desktop 1.2.3", "rift-core 1.2.3"] : ["rift-core 1.2.3", "rift-fuzz 0.0.0"], true));
  const before = snapshot(f.base);
  const expected = expectedUpdate(before, "3.0.1");
  for (const file of ["Cargo.lock", "fuzz/Cargo.lock"])
    expected.set(file, expected.get(file).replace(/"(rift-core|rift-desktop) 1\.2\.3"/g, '"$1 3.0.1"'));
  setVersion("3.0.1", f.base);
  assert.equal(checkVersions("v3.0.1", f.base), "3.0.1");
  assert.deepEqual(snapshot(f.base), expected);
});

test("same version is a true no-op, including existing formatting, modes and timestamps", (t) => {
  const f = fixture(t);
  f.put("desktop/package.json", f.get("desktop/package.json").replace('"version" : "1.2.3"', '"ver\\u0073ion" : "\\u0031.2.3"'));
  const before = snapshot(f.base);
  const metadata = versionFiles.map((name) => lstatSync(path.join(f.base, name)));
  assert.equal(setVersion("1.2.3", f.base), "1.2.3");
  assert.deepEqual(snapshot(f.base), before);
  versionFiles.forEach((name, index) => {
    const after = lstatSync(path.join(f.base, name));
    assert.equal(after.ino, metadata[index].ino);
    assert.equal(after.mtimeMs, metadata[index].mtimeMs);
    assert.equal(after.mode, metadata[index].mode);
  });
});

test("version setting preserves CRLF and file permission bits", (t) => {
  const f = fixture(t);
  for (const file of versionFiles) f.put(file, f.get(file).replaceAll("\n", "\r\n"));
  if (process.platform !== "win32") chmodSync(path.join(f.base, "Cargo.toml"), 0o640);
  const before = snapshot(f.base);
  setVersion("0.0.0", f.base);
  assert.equal(checkVersions("v0.0.0", f.base), "0.0.0");
  for (const file of versionFiles) {
    const actual = f.get(file);
    assert.ok(!/(?<!\r)\n/.test(actual), `${file} lost CRLF`);
    assert.equal(actual.split("\r\n").length, before.get(file).split("\r\n").length);
  }
  assert.equal(f.get("fuzz/Cargo.toml"), before.get("fuzz/Cargo.toml"));
  if (process.platform !== "win32") assert.equal(lstatSync(path.join(f.base, "Cargo.toml")).mode & 0o777, 0o640);
});

test("only stable explicit versions are accepted, without semver ordering policy", (t) => {
  const f = fixture(t);
  const before = snapshot(f.base);
  for (const bad of [undefined, null, 2, "", "v1.2.3", "01.2.3", "1.02.3", "1.2.03", "1.2", "1.2.3-beta.1", "1.2.3+build", " 1.2.3", "1.2.3\n", "1.2.3/../x"])
    assert.throws(() => setVersion(bad, f.base));
  assert.deepEqual(snapshot(f.base), before);
  setVersion("0.1.0", f.base);
  assert.equal(checkVersions("v0.1.0", f.base), "0.1.0");
});

test("missing, malformed, ambiguous or inconsistent current inputs never change files", (t) => {
  const mutations = [
    (f) => rmSync(path.join(f.base, "Cargo.lock")),
    (f) => rmSync(path.join(f.base, "fuzz/Cargo.toml")),
    (f) => { rmSync(path.join(f.base, "desktop/package.json")); mkdirSync(path.join(f.base, "desktop/package.json")); },
    (f) => f.put("Cargo.toml", f.get("Cargo.toml").replace("[workspace.package]", "[package]")),
    (f) => f.put("Cargo.toml", f.get("Cargo.toml") + '[workspace.package]\nversion = "1.2.3"\n'),
    (f) => f.put("Cargo.toml", f.get("Cargo.toml").replace('edition = "2021"', 'version = "1.2.3"')),
    (f) => f.put("Cargo.toml", f.get("Cargo.toml").replace('edition = "2021"', '"version" = "1.2.3"')),
    (f) => f.put("Cargo.toml", f.get("Cargo.toml").replace("1.2.3\"  #", "1.2.3-beta.1\"  #")),
    (f) => f.put("desktop/package.json", '{"version":"1.2.3",'),
    (f) => f.put("desktop/package.json", '{"version":"1.2.3","version":"1.2.3"}'),
    (f) => f.put("desktop/package.json", '{"version":"1.2.3","ver\\u0073ion":"1.2.3"}'),
    (f) => f.put("desktop/package.json", '{"version":123}'),
    (f) => f.put("desktop/package.json", '{"nested":{"version":"1.2.3"}}'),
    (f) => f.put("desktop/src-tauri/tauri.conf.json", '{"version":"9.9.9"}'),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace('name = "rift-desktop"\nversion = "1.2.3"', 'name = "rift-desktop"\nversion = "1.2.4"')),
    (f) => f.put("fuzz/Cargo.lock", f.get("fuzz/Cargo.lock").replace('name = "rift-core"\nversion = "1.2.3"', 'name = "rift-core"\nversion = "0.0.0"')),
    (f) => f.put("fuzz/Cargo.lock", f.get("fuzz/Cargo.lock").replace('name = "rift-fuzz"\nversion = "0.0.0"', 'name = "rift-fuzz"\nversion = "1.2.3"')),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock") + locked("rift-core", "1.2.3")),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock") + locked("unknown-local", "1.2.3")),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace('name = "rift-core"\n', `name = "rift-core"\nsource = "${source}"\n`)),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace(' "rift-core",', ' "rift-core 9.9.9",')),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace(' "rift-core",', ` "rift-core 1.2.3 (${source})",`)),
    (f) => f.put("fuzz/Cargo.lock", f.get("fuzz/Cargo.lock").replace(' "rift-core",', ' "rift-desktop 1.2.3",')),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace(' "rift-core",', ' "rift-core 1.2.3 broken",')),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace("version = 4", "version = 99")),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace('checksum = "', 'checksum = "broken"\nchecksum = "')),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace(' "rift-core",\n', ' "rift-core",\n malformed\n')),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock").replace(' "rift-core",\n', ' "rift-core"\n "third-party 1.2.3"\n')),
    (f) => f.put("Cargo.lock", f.get("Cargo.lock") + "unexpected = { broken\n"),
    (f) => f.put("fuzz/Cargo.lock", f.get("fuzz/Cargo.lock") + '[[package]]\nname = "incomplete"\n'),
  ];
  for (const [index, mutate] of mutations.entries()) {
    const f = fixture(t);
    mutate(f);
    const before = snapshot(f.base);
    assert.throws(() => setVersion("2.0.0", f.base), `malformed case ${index}`);
    assert.deepEqual(snapshot(f.base), before, `malformed case ${index} changed files`);
  }
});

test("same-version requests still reject malformed local references", (t) => {
  const f = fixture(t);
  f.put("fuzz/Cargo.lock", f.get("fuzz/Cargo.lock").replace(' "rift-core",', ' "rift-core 1.0.0",'));
  const before = snapshot(f.base);
  assert.throws(() => setVersion("1.2.3", f.base), /local dependency reference/);
  assert.deepEqual(snapshot(f.base), before);
});

test("a real staging I/O failure leaves original files and no temporary siblings", { skip: process.platform === "win32" || process.getuid?.() === 0 }, (t) => {
  const f = fixture(t);
  const directory = path.join(f.base, "desktop");
  chmodSync(directory, 0o555);
  try {
    const before = snapshot(f.base);
    assert.throws(() => setVersion("2.0.0", f.base), /EACCES|EPERM/);
    assert.deepEqual(snapshot(f.base), before);
  } finally { chmodSync(directory, 0o755); }
});

test("CLI rejects missing, extra and invalid argv without editing its exported root", (t) => {
  const f = fixture(t);
  const entry = installCli(f);
  const before = snapshot(f.base);
  for (const args of [[], ["2.0.0", "extra"], ["v2.0.0"], ["--help"], ["2.0.0-beta.1"], ["02.0.0"], ["2.0.0\n"]]) {
    const result = spawnSync(process.execPath, [entry, ...args], { cwd: f.base, encoding: "utf8" });
    assert.equal(result.status, 1, JSON.stringify(args));
    assert.match(result.stderr, /Usage|stable/);
    assert.equal(result.stdout, "");
    assert.deepEqual(snapshot(f.base), before);
  }
});

test("CLI resolves the public root from its module, not cwd, and needs no external tools", (t) => {
  const f = fixture(t);
  const other = fixture(t);
  const entry = installCli(f);
  const before = snapshot(f.base);
  const outsideBefore = snapshot(other.base);
  const result = spawnSync(process.execPath, [entry, "4.5.6"], { cwd: other.base, encoding: "utf8", env: { ...process.env, PATH: "", GIT_DIR: path.join(other.base, ".git") } });
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stdout, "4.5.6\n");
  assert.equal(result.stderr, "");
  assert.equal(checkVersions("v4.5.6", f.base), "4.5.6");
  assert.deepEqual(snapshot(f.base), expectedUpdate(before, "4.5.6"));
  assert.deepEqual(snapshot(other.base), outsideBefore);
  const repeated = spawnSync(process.execPath, ["tooling/version.mjs", "4.5.6"], { cwd: f.base, encoding: "utf8" });
  assert.equal(repeated.status, 0, repeated.stderr);
  assert.deepEqual(snapshot(f.base), expectedUpdate(before, "4.5.6"));
});
